def filter_tes(tes_raw, skenario, cfg: Cfg):
    hc = cfg.hazard_col_map.get(skenario, skenario)
    lst = []; stats = {}
    for kat, gk in tes_raw.items():
        n  = len(gk)
        gv = (gk[gk[hc] < cfg.tes_hazard_threshold].copy()
              if hc in gk.columns else gk.copy())
        stats[kat] = {"total": n, "valid": len(gv)}
        if len(gv) > 0:
            gv["kategori"] = kat
            lst.append(gv[["geometry", "kategori"]])
    if not lst:
        log(f"Tidak ada TES valid untuk {skenario.upper()}!", "ERR")
        return None, stats
    tes_v = gpd.GeoDataFrame(pd.concat(lst, ignore_index=True), crs=cfg.target_crs)
    log(f"  TES valid: {sum(v['valid'] for v in stats.values())}/"
        f"{sum(v['total'] for v in stats.values())}", "OK")
    return tes_v, stats


