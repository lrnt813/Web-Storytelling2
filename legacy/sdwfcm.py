def tbl(headers, rows, indent=4):
    if not rows: log("(kosong)", "WARN"); return
    cw = [max(len(str(h)), max((len(str(r[i])) for r in rows), default=0))
          for i, h in enumerate(headers)]
    pad = " " * indent
    top = pad + "┌" + "┬".join("─" * (w + 2) for w in cw) + "┐"
    sep = pad + "├" + "┼".join("─" * (w + 2) for w in cw) + "┤"
    bot = pad + "└" + "┴".join("─" * (w + 2) for w in cw) + "┘"
    def fr(cells, bold=False):
        parts = []
        for cell, w in zip(cells, cw):
            s = str(cell)
            try: float(s); s = s.rjust(w)
            except: s = s.ljust(w)
            parts.append(f" {C.B + C.CY if bold else C.W}{s}{C.R} ")
        return pad + "│" + "│".join(parts) + "│"
    print(top); print(fr(headers, True)); print(sep)
    for r in rows: print(fr(r))
    print(bot)

