def build_road_graph(roads, skenario, intensity, cfg: Cfg):
    hc = cfg.hazard_col_map.get(skenario, skenario)
    G  = nx.Graph(); n_rm = n_ok = 0
    for _, row in roads.iterrows():
        geom = row.geometry
        if geom is None or geom.is_empty: continue
        if (cfg.norm_haz(int(row[hc]) if hc in row.index else 0)
                * intensity >= cfg.impact_closure_threshold):
            n_rm += 1; continue
        n_ok += 1
        lines = [geom] if geom.geom_type == "LineString" else list(geom.geoms)
        for line in lines:
            coords = list(line.coords)
            for i in range(len(coords) - 1):
                u = (round(coords[i][0], 2),     round(coords[i][1], 2))
                v = (round(coords[i + 1][0], 2), round(coords[i + 1][1], 2))
                sl = LineString([coords[i], coords[i + 1]]).length
                if G.has_edge(u, v): G[u][v]["weight"] = min(G[u][v]["weight"], sl)
                else: G.add_edge(u, v, weight=sl)
    nl = np.array(list(G.nodes())) if G.nodes() else np.empty((0, 2))
    tn = cKDTree(nl) if len(nl) else None
    log(f"  [NX] closed={n_rm}, ok={n_ok}", "DATA")
    return G, nl, tn

def _snap(G, tn, nl, xy, max_snap=300):
    if tn is None or len(nl) == 0: return None
    d, i = tn.query(xy, k=1)
    if (d if np.isscalar(d) else d[0]) > max_snap: return None
    nd = tuple(nl[i if np.isscalar(i) else i[0]])
    return nd if G.has_node(nd) else None


