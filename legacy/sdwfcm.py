    mcols = ["algoritma", "n_cluster", "silhouette", "calinski_harabasz",
             "davies_bouldin", "moran_cluster", "ambig_pct", "waktu_tes_mean"]
    av   = [c for c in mcols if c in df.columns]
    tbl(av, [[str(r.get(c, "—")) for c in av] for _, r in df.iterrows()])
    log("Evaluasi selesai", "OK"); return df


