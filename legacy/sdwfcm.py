def build_weights(gdf, G=None, nl=None, tn=None):
    section("Spatial Weight Matrix", 1)
    n = len(gdf)
    try: w = Rook.from_dataframe(gdf, ids=None, silence_warnings=True)
    except: w = Queen.from_dataframe(gdf, silence_warnings=True)

    islands = [i for i, nb in w.neighbors.items() if len(nb) == 0]
    if islands:
        try:
            wk = KNN.from_dataframe(gdf, k=2, silence_warnings=True)
            for i in islands:
                w.neighbors[i] = list(wk.neighbors[i])
                w.weights[i]   = [1.0] * len(wk.neighbors[i])
        except Exception as e: log(f"KNN fallback gagal: {e}", "WARN")

    def _add(u, v):
        for a, b in [(u, v), (v, u)]:
            if b not in w.neighbors.get(a, []):
                w.neighbors[a] = list(w.neighbors.get(a, [])) + [b]
                w.weights[a]   = list(w.weights.get(a, []))   + [1.0]

    Gx = nx.Graph(); Gx.add_nodes_from(range(n))
    for i, nbs in w.neighbors.items():
        for j in nbs: Gx.add_edge(i, j)
    comps = list(nx.connected_components(Gx))
    if len(comps) > 1:
        cents  = np.array([[g.centroid.x, g.centroid.y] for g in gdf.geometry])
        cl     = [sorted(c) for c in comps]; tu = cKDTree(cents)
        u2c    = np.zeros(n, int)
        for ci, cu in enumerate(cl):
            for u in cu: u2c[u] = ci
        parent = list(range(len(comps)))
        def find(x):
            while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
            return x
        def union(a, b):
            ra, rb = find(a), find(b)
            if ra != rb: parent[rb] = ra; return True
            return False
        for ci in sorted(range(len(comps)), key=lambda i: len(cl[i])):
            if find(ci) == find(0) and ci != 0: continue
            cc = cents[cl[ci]].mean(0); _, idxs = tu.query(cc, k=min(200, n))
            for idx in idxs:
                cj = int(u2c[int(idx)])
                if find(cj) != find(ci):
                    diffs   = cents[cl[ci]] - cents[int(idx)]
                    nearest = cl[ci][int(np.argmin(np.linalg.norm(diffs, axis=1)))]
                    _add(nearest, int(idx)); union(ci, cj); break
    try:
        w.transform = 'r'
        log("Spatial weight: row-standardized ✔", "OK")
    except:
        for i in list(w.neighbors.keys()):
            wt = w.weights.get(i, []); total = sum(wt) or 1.0
            if total > 0: w.weights[i] = [x / total for x in wt]
    kv("Unit (N)", w.n)
    kv("Rata-rata tetangga", f"{w.mean_neighbors:.2f}")
    log("Spatial weight siap", "OK"); return w


