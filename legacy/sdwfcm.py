def build_pandana_network(roads, cfg: Cfg):
    if roads is None: return None, None, None, None
    log("Membangun Pandana Network...", "DATA")
    node_dict = {}; edge_rows = []

    def _node(x, y):
        k = (round(x, 2), round(y, 2))
        if k not in node_dict: node_dict[k] = len(node_dict)
        return node_dict[k], k[0], k[1]

    for _, row in roads.iterrows():
        geom = row.geometry
        if geom is None or geom.is_empty: continue
        lines = [geom] if geom.geom_type == "LineString" else list(geom.geoms)
        for line in lines:
            coords = list(line.coords)
            for i in range(len(coords) - 1):
                u, _, _ = _node(*coords[i][:2])
                v, _, _ = _node(*coords[i + 1][:2])
                sl = LineString([coords[i], coords[i + 1]]).length
                ei = {"from": u, "to": v, "weight_base": sl}
                for hk, hc in cfg.hazard_col_map.items():
                    ei[hc] = int(row[hc]) if hc in row.index else 0
                edge_rows.append(ei)

    if not node_dict: log("Tidak ada node", "ERR"); return None, None, None, None
    nc = list(node_dict.keys()); ni = list(node_dict.values())
    node_df = pd.DataFrame({"x": [c[0] for c in nc], "y": [c[1] for c in nc]},
                           index=ni)
    edge_df = pd.DataFrame(edge_rows)
    try:
        net = pandana.Network(node_df["x"], node_df["y"],
                              edge_df["from"], edge_df["to"],
                              edge_df[["weight_base"]], twoway=True)
        log(f"Pandana: {len(node_df)} node, {len(edge_df)} edge", "OK")
        return net, node_df, edge_df, node_dict
    except Exception as e:
        log(f"Pandana gagal: {e} → fallback NetworkX", "WARN")
        return None, None, None, node_dict

def apply_pandana_weights(net, edge_df, skenario, intensity, cfg: Cfg):
    if net is None or edge_df is None: return
    hc    = cfg.hazard_col_map.get(skenario, skenario)
    inf_w = cfg.unreachable_time * cfg.walking_speed_m_per_min * 100.0
    base  = edge_df["weight_base"].values.copy()
    if hc in edge_df.columns:
        nh = np.vectorize(cfg.norm_haz)(edge_df[hc].values.astype(int))
        w_ = np.where(nh * intensity >= cfg.impact_closure_threshold, inf_w, base)
    else:
        w_ = base
    net.edge_weights = pd.DataFrame({"weight_base": w_})
    net.precompute(cfg.unreachable_time * cfg.walking_speed_m_per_min * 1.1)
    log(f"  Pandana weights: {int((w_ >= inf_w * 0.9).sum())} jalan ditutup", "DATA")

def query_pandana(net, cx, cy, tx, ty, t_pen, cfg: Cfg):
    if net is None: return None
    max_d = t_pen * cfg.walking_speed_m_per_min
    try:
        net.set_pois("tes", max_d, 1, pd.Series(tx), pd.Series(ty))
        net.get_node_ids(pd.Series(cx), pd.Series(cy))
        d = net.nearest_pois(max_d, "tes", 1, "weight_base")[1].values
        t = d / cfg.walking_speed_m_per_min
        return np.where((d >= max_d) | np.isinf(t), t_pen, t)
    except Exception as e:
        log(f"  Pandana query gagal: {e}", "WARN"); return None


