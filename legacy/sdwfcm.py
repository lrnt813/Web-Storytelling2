def _read_gpkg(path, crs_target, geom_types=None):
    gdf = gpd.read_file(path)
    if gdf.crs is None:
        gdf = gdf.set_crs("EPSG:4326")
    if gdf.crs.to_epsg() != int(crs_target.split(":")[1]):
        gdf = gdf.to_crs(crs_target)
    if geom_types:
        gdf = gdf[gdf.geometry.geom_type.isin(geom_types)]
    return gdf.reset_index(drop=True)

def load_data(cfg: Cfg):
    section("STEP 1 — Load Data", 1)
    gdf = _read_gpkg(cfg.input_file, cfg.target_crs)
    gdf = gdf[gdf.geometry.notna() & ~gdf.geometry.is_empty].reset_index(drop=True)
    kv("Jumlah grid", len(gdf)); kv("CRS", gdf.crs.to_epsg())
    log("Data dimuat", "OK"); return gdf

def load_road_network(cfg: Cfg):
    section("STEP 1b — Load Jalan & TES", 1)
    roads = None
    if os.path.exists(cfg.roads_file):
        roads = _read_gpkg(cfg.roads_file, cfg.target_crs,
                           ["LineString", "MultiLineString"])
        for c in cfg.hazard_col_map.values():
            if c not in roads.columns: roads[c] = 0
        log(f"Jalan: {len(roads)} segmen", "OK")
    else:
        log(f"File jalan tidak ada: {cfg.roads_file}", "WARN")

    tes = {}
    for kat, fp in cfg.tes_files.items():
        if os.path.exists(fp):
            t = _read_gpkg(fp, cfg.target_crs, ["Point"])
            for c in cfg.hazard_col_map.values():
                if c not in t.columns: t[c] = 0
            tes[kat] = t
            log(f"TES {kat:<15}: {len(t)} titik", "DATA")
        else:
            log(f"TES tidak ada: {fp}", "WARN")
    return roads, tes


