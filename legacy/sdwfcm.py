# 16. PENENTUAN K OPTIMAL
# ══════════════════════════════════════════════════════════════════════
def determine_k(X_pca, skenario, cfg: Cfg, suffix=""):
    section(f"K Optimal Baseline [{skenario.upper()}]", 2)
    ks = list(cfg.k_range); inertias = []
    from sklearn.cluster import KMeans
    for k in tqdm(ks, desc="  Elbow", leave=False, colour="magenta"):
        try:
            km = KMeans(n_clusters=k, random_state=42,
                        n_init=cfg.elbow_n_init, max_iter=cfg.elbow_max_iter)
            km.fit(X_pca); inertias.append(km.inertia_)
        except Exception as e:
            log(f"  k={k} gagal: {e}", "WARN"); inertias.append(np.nan)

    ia      = np.array(inertias)
    valid_k = [ks[i] for i in range(len(ks)) if not np.isnan(ia[i])]
    valid_i = ia[~np.isnan(ia)].tolist()
    k_opt   = None
    if KNEED_OK and len(valid_k) >= 3:
        try:
            kl    = KneeLocator(valid_k, valid_i, curve="convex",
                                direction="decreasing", interp_method="interp1d")
            k_opt = kl.knee
        except: pass
    if k_opt is None and len(valid_i) >= 2:
        rel   = np.abs(np.diff(valid_i)) / (np.array(valid_i[:-1]) + 1e-10)
        k_opt = valid_k[int(np.argmax(rel)) + 1]
    if k_opt is None: k_opt = 4
    if k_opt <= cfg.k_min_parsimony:
        ge3 = [k for k in valid_k if k >= 3]
        ie3 = [valid_i[valid_k.index(k)] for k in ge3]
        if len(ge3) >= 2:
            rel   = np.abs(np.diff(ie3)) / (np.array(ie3[:-1]) + 1e-10)
            k_opt = ge3[int(np.argmax(rel)) + 1]
        elif ge3: k_opt = ge3[0]
        else:     k_opt = 3

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(ks, inertias, "o-", color="#3498DB", lw=2.5, ms=9)
    ax.fill_between(ks, inertias, alpha=0.08, color="#3498DB")
    ax.axvline(k_opt, ls="-.", color="#E74C3C", lw=2.2,
               label=f"K Optimal = {k_opt}")
    ax.set_xlabel("Jumlah Klaster (K)", fontsize=12)
    ax.set_ylabel("Inertia (SSE)", fontsize=12)
    ax.set_title(f"Elbow Method — {skenario.upper()} | K Optimal = {k_opt}",
                 fontsize=12, fontweight="bold")
    ax.set_xticks(ks); ax.legend(); ax.grid(True, alpha=0.3)
    savefig(fig, f"{cfg.output_dir}/elbow_{skenario}{suffix}.png", 120)
    kv("K FINAL", k_opt, ok=True); return k_opt


